    provider VARCHAR(32) NOT NULL,
    subject VARCHAR(80) NOT NULL,
    model VARCHAR(255) NOT NULL,
    status VARCHAR(24) NOT NULL,
    reason VARCHAR(80),
    checked_at TIMESTAMP WITH TIME ZONE NOT NULL,
