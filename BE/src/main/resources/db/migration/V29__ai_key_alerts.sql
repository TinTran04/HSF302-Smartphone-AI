CREATE TABLE ai_key_alerts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    config_id BIGINT NOT NULL REFERENCES ai_provider_configs(id) ON DELETE CASCADE,
    status VARCHAR(32) NOT NULL,
    reason VARCHAR(64),
    backup_failure_reason VARCHAR(64),
    detected_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_ai_key_alerts_config_id ON ai_key_alerts(config_id, id DESC);
