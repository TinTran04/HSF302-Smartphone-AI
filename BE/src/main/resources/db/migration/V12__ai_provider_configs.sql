CREATE TABLE ai_provider_configs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider VARCHAR(255) NOT NULL, model VARCHAR(255) NOT NULL,
    key_cipher TEXT NOT NULL, tested BOOLEAN NOT NULL DEFAULT FALSE, active BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL, version BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX idx_ai_provider_configs_provider ON ai_provider_configs(provider, id);
