CREATE TABLE ai_key_identities (
    provider VARCHAR(32) NOT NULL,
    key_fingerprint VARCHAR(64) NOT NULL,
    name VARCHAR(80) NOT NULL,
    last_primary_at TIMESTAMP WITH TIME ZONE,
    PRIMARY KEY (provider, key_fingerprint)
);

CREATE TABLE ai_key_switch_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider VARCHAR(32) NOT NULL,
    from_name VARCHAR(80),
    from_masked_key VARCHAR(32),
    to_name VARCHAR(80) NOT NULL,
    to_masked_key VARCHAR(32) NOT NULL,
    actor VARCHAR(255) NOT NULL,
    changed_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_ai_key_switch_provider ON ai_key_switch_history(provider, id);
