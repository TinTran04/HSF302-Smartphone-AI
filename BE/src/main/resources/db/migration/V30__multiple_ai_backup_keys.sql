CREATE TABLE ai_backup_keys (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    config_id BIGINT NOT NULL REFERENCES ai_provider_configs(id) ON DELETE CASCADE,
    name VARCHAR(80) NOT NULL,
    priority INTEGER NOT NULL,
    key_cipher TEXT NOT NULL,
    masked_key VARCHAR(32) NOT NULL,
    last_status VARCHAR(32) NOT NULL DEFAULT 'UNKNOWN',
    last_failure_reason VARCHAR(64),
    last_checked_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uq_ai_backup_priority UNIQUE(config_id, priority)
);
