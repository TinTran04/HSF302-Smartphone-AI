CREATE TABLE ai_guest_sessions (
    id UUID PRIMARY KEY, token_hash VARCHAR(64) NOT NULL UNIQUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL, expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    message_count INTEGER NOT NULL DEFAULT 0 CHECK(message_count >= 0), revoked BOOLEAN NOT NULL DEFAULT FALSE,
    version BIGINT NOT NULL DEFAULT 0
);
CREATE TABLE ai_conversations (
    id UUID PRIMARY KEY, user_id UUID REFERENCES users(id), guest_id UUID REFERENCES ai_guest_sessions(id),
    topic VARCHAR(255) NOT NULL, title VARCHAR(255) NOT NULL, created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    product_ids TEXT NOT NULL, version BIGINT NOT NULL DEFAULT 0,
    CHECK ((user_id IS NOT NULL AND guest_id IS NULL) OR (user_id IS NULL AND guest_id IS NOT NULL))
);
CREATE TABLE ai_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, conversation_id UUID NOT NULL REFERENCES ai_conversations(id),
    role VARCHAR(255) NOT NULL, content TEXT NOT NULL, sources_json TEXT NOT NULL, created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE ai_topic_switch_requests (
    id UUID PRIMARY KEY, conversation_id UUID NOT NULL REFERENCES ai_conversations(id), suggested_topic VARCHAR(255) NOT NULL,
    question TEXT NOT NULL, status VARCHAR(255) NOT NULL, new_conversation_id UUID REFERENCES ai_conversations(id),
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL, version BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX idx_ai_conversations_user ON ai_conversations(user_id);
CREATE INDEX idx_ai_conversations_guest ON ai_conversations(guest_id);
CREATE INDEX idx_ai_messages_conversation ON ai_messages(conversation_id, id);
